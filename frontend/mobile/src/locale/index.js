import { ref } from 'vue';

const STORAGE_KEY = 'planner_locale';
export const availableLocales = [
  { value: 'zh', label: '中文' },
  { value: 'en', label: 'English' },
];

export const locale = ref('zh');

export function initLocale() {
  try {
    const stored = uni.getStorageSync(STORAGE_KEY);
    if (stored === 'zh' || stored === 'en') locale.value = stored;
  } catch (e) {}
  applyTabBarTitles();
}

export function setLocale(l) {
  if (l !== 'zh' && l !== 'en') return;
  locale.value = l;
  try { uni.setStorageSync(STORAGE_KEY, l); } catch (e) {}
  applyTabBarTitles();
}

export function applyTabBarTitles() {
  const items = [
    { index: 0, text: t('tab.home') },
    { index: 1, text: t('tab.calendar') },
    { index: 2, text: t('tab.habits') },
    { index: 3, text: t('tab.stats') },
  ];
  items.forEach((item) => {
    try {
      uni.setTabBarItem({ index: item.index, text: item.text });
    } catch (e) {}
  });
}

